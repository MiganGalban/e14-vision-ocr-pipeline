-- 8. FUNCIÓN TRANSACCIONAL ATÓMICA ACID (Sin JSON/JSONB)
CREATE OR REPLACE FUNCTION public.insert_e14_atomic(
    p_archivo_origen TEXT,
    p_puesto_id INTEGER,
    p_dp_mesa TEXT,
    p_dp_lugr TEXT,
    p_cod_x TEXT,
    p_s_cod_x NUMERIC,
    p_cod_x_2 TEXT,
    p_s_cod_x_2 NUMERIC,
    p_barras_1 TEXT,
    p_s_barras_1 NUMERIC,
    p_barras_2 TEXT,
    p_s_barras_2 NUMERIC,
    p_es_fallo_total BOOLEAN,
    p_err_alineacion BOOLEAN,
    p_err_inferencia_ocr BOOLEAN,
    p_err_puesto_no_resuelto BOOLEAN,
    p_flag_divipole_mismatch BOOLEAN,
    p_flag_archivo_vs_ocr_diff BOOLEAN,
    p_flag_baja_conf_encabezado BOOLEAN,
    p_flag_baja_conf_votos BOOLEAN,
    p_flag_caracter_anomalo BOOLEAN,
    p_flag_descuadre_aritmetico BOOLEAN,
    p_flag_omr_recuento_ambiguo BOOLEAN,
    p_flag_sin_firmas_jurados BOOLEAN,
    p_t_e11 INTEGER,
    p_t_urna INTEGER,
    p_t_inc INTEGER,
    p_v_a INTEGER,
    p_v_b INTEGER,
    p_v_blan INTEGER,
    p_v_nulo INTEGER,
    p_v_s_mrc INTEGER,
    p_suma_t INTEGER,
    p_confianza_promedio_ocr NUMERIC,
    p_vp_campos TEXT[],
    p_vp_indices INTEGER[],
    p_vp_preds TEXT[],
    p_vp_confs NUMERIC[],
    p_vp_crops TEXT[],
    p_aud_observ_jud BOOLEAN,
    p_aud_re_count_si BOOLEAN,
    p_aud_re_count_no BOOLEAN,
    p_aud_count_req_by BOOLEAN,
    p_aud_on_behalf_of BOOLEAN,
    p_aud_firma_j1 BOOLEAN,
    p_aud_firma_j2 BOOLEAN,
    p_aud_firma_j3 BOOLEAN,
    p_aud_firma_j4 BOOLEAN,
    p_aud_firma_j5 BOOLEAN,
    p_aud_firma_j6 BOOLEAN,
    p_aud_firma_cc_j1 BOOLEAN,
    p_aud_firma_cc_j2 BOOLEAN,
    p_aud_firma_cc_j3 BOOLEAN,
    p_aud_firma_cc_j4 BOOLEAN,
    p_aud_firma_cc_j5 BOOLEAN,
    p_aud_firma_cc_j6 BOOLEAN,
    p_ap_campos TEXT[],
    p_ap_valores NUMERIC[]
)
RETURNS TABLE (out_status TEXT, out_id_divipole INTEGER)
LANGUAGE plpgsql
SECURITY DEFINER
SET search_path = public
AS $$
DECLARE
    v_id_divipole INTEGER;
    v_id_votos INTEGER;
    v_id_auditoria INTEGER;
    v_has_banderas BOOLEAN;
    v_has_votos BOOLEAN;
    v_has_votos_prec BOOLEAN;
    v_has_auditoria BOOLEAN;
    v_has_audit_prec BOOLEAN;
    v_is_manual_fail BOOLEAN;
    v_err_duplicado_mesa BOOLEAN := FALSE;
    v_req_revision BOOLEAN;
    v_constraint_name TEXT;
BEGIN
    v_req_revision := (
        p_err_alineacion OR p_err_inferencia_ocr OR p_err_puesto_no_resuelto
        OR p_flag_divipole_mismatch OR p_flag_archivo_vs_ocr_diff
        OR p_flag_baja_conf_encabezado OR p_flag_baja_conf_votos
        OR p_flag_caracter_anomalo OR p_flag_descuadre_aritmetico
        OR p_flag_omr_recuento_ambiguo OR p_flag_sin_firmas_jurados
    );

    -- 1. Idempotencia y verificación de completitud en tablas hijas
    SELECT d.id INTO v_id_divipole
    FROM public.divipole d
    WHERE d.archivo_origen = p_archivo_origen;

    IF v_id_divipole IS NOT NULL THEN
        SELECT (d.dp_mesa IS NULL AND d.cod_x IS NULL AND d.cod_x_2 IS NULL AND d.barras_1 IS NULL AND d.req_revision = TRUE)
        INTO v_is_manual_fail
        FROM public.divipole d
        WHERE d.id = v_id_divipole;

        SELECT EXISTS(SELECT 1 FROM public.revision_banderas rb WHERE rb.id_divipole = v_id_divipole) INTO v_has_banderas;
        SELECT EXISTS(SELECT 1 FROM public.votos v WHERE v.id_divipole = v_id_divipole) INTO v_has_votos;
        SELECT EXISTS(
            SELECT 1 FROM public.votos v
            JOIN public.votos_precision vp ON vp.id_votos = v.id
            WHERE v.id_divipole = v_id_divipole
        ) INTO v_has_votos_prec;
        SELECT EXISTS(SELECT 1 FROM public.auditoria a WHERE a.id_divipole = v_id_divipole) INTO v_has_auditoria;
        SELECT EXISTS(
            SELECT 1 FROM public.auditoria a
            JOIN public.auditoria_precision ap ON ap.id_auditoria = a.id
            WHERE a.id_divipole = v_id_divipole
        ) INTO v_has_audit_prec;

        IF v_has_banderas AND (v_is_manual_fail OR (v_has_votos AND v_has_votos_prec AND v_has_auditoria AND v_has_audit_prec)) THEN
            RETURN QUERY SELECT 'skipped'::TEXT, v_id_divipole;
            RETURN;
        ELSE
            DELETE FROM public.divipole d WHERE d.id = v_id_divipole;
        END IF;
    END IF;

    -- 2. Insertar cabecera en divipole capturando colisión uk_puesto_mesa
    BEGIN
        INSERT INTO public.divipole (
            archivo_origen, puesto_id, dp_mesa, dp_lugr,
            cod_x, s_cod_x, cod_x_2, s_cod_x_2,
            barras_1, s_barras_1, barras_2, s_barras_2, req_revision
        )
        VALUES (
            p_archivo_origen::VARCHAR(32),
            p_puesto_id,
            p_dp_mesa::VARCHAR(3),
            p_dp_lugr::VARCHAR(150),
            p_cod_x::VARCHAR(15),
            p_s_cod_x::NUMERIC(3,2),
            p_cod_x_2::VARCHAR(15),
            p_s_cod_x_2::NUMERIC(3,2),
            p_barras_1::VARCHAR(20),
            p_s_barras_1::NUMERIC(3,2),
            p_barras_2::VARCHAR(20),
            p_s_barras_2::NUMERIC(3,2),
            v_req_revision
        )
        RETURNING id INTO v_id_divipole;
    EXCEPTION
        WHEN unique_violation THEN
            GET STACKED DIAGNOSTICS v_constraint_name = CONSTRAINT_NAME;
            IF v_constraint_name = 'uk_puesto_mesa' THEN
                v_err_duplicado_mesa := TRUE;
                v_req_revision := TRUE;
                INSERT INTO public.divipole (
                    archivo_origen, puesto_id, dp_mesa, dp_lugr,
                    cod_x, s_cod_x, cod_x_2, s_cod_x_2,
                    barras_1, s_barras_1, barras_2, s_barras_2, req_revision
                )
                VALUES (
                    p_archivo_origen::VARCHAR(32),
                    p_puesto_id,
                    NULL,
                    p_dp_lugr::VARCHAR(150),
                    p_cod_x::VARCHAR(15),
                    p_s_cod_x::NUMERIC(3,2),
                    p_cod_x_2::VARCHAR(15),
                    p_s_cod_x_2::NUMERIC(3,2),
                    p_barras_1::VARCHAR(20),
                    p_s_barras_1::NUMERIC(3,2),
                    p_barras_2::VARCHAR(20),
                    p_s_barras_2::NUMERIC(3,2),
                    TRUE
                )
                RETURNING id INTO v_id_divipole;
            ELSE
                RAISE;
            END IF;
    END;

    -- 3. Insertar las 12 banderas granulares
    INSERT INTO public.revision_banderas (
        id_divipole, err_alineacion, err_inferencia_ocr, err_puesto_no_resuelto,
        err_duplicado_mesa, flag_divipole_mismatch, flag_archivo_vs_ocr_diff,
        flag_baja_conf_encabezado, flag_baja_conf_votos, flag_caracter_anomalo,
        flag_descuadre_aritmetico, flag_omr_recuento_ambiguo, flag_sin_firmas_jurados
    )
    VALUES (
        v_id_divipole, p_err_alineacion, p_err_inferencia_ocr, p_err_puesto_no_resuelto,
        v_err_duplicado_mesa, p_flag_divipole_mismatch, p_flag_archivo_vs_ocr_diff,
        p_flag_baja_conf_encabezado, p_flag_baja_conf_votos, p_flag_caracter_anomalo,
        p_flag_descuadre_aritmetico, p_flag_omr_recuento_ambiguo, p_flag_sin_firmas_jurados
    );

    IF p_es_fallo_total THEN
        RETURN QUERY SELECT 'marked_for_manual_review'::TEXT, v_id_divipole;
        RETURN;
    END IF;

    -- 4. Insertar votos consolidados
    INSERT INTO public.votos (
        id_divipole, t_e11, t_urna, t_inc, v_a, v_b, v_blan, v_nulo, v_s_mrc, suma_t, confianza_promedio_ocr
    )
    VALUES (
        v_id_divipole, p_t_e11, p_t_urna, p_t_inc, p_v_a, p_v_b,
        p_v_blan, p_v_nulo, p_v_s_mrc, p_suma_t, p_confianza_promedio_ocr::NUMERIC(3,2)
    )
    RETURNING id INTO v_id_votos;

    -- 5. Insertar votos_precision
    INSERT INTO public.votos_precision (
        id_votos, campo_nombre, casilla_index, prediccion_raw, confianza, data_recorte
    )
    SELECT
        v_id_votos,
        u.campo_nombre::VARCHAR(10),
        u.casilla_index,
        u.prediccion_raw::VARCHAR(10),
        u.confianza::NUMERIC(3,2),
        u.data_recorte
    FROM UNNEST(
        p_vp_campos, p_vp_indices, p_vp_preds, p_vp_confs, p_vp_crops
    ) AS u(campo_nombre, casilla_index, prediccion_raw, confianza, data_recorte);

    -- 6. Insertar auditoria OMR
    INSERT INTO public.auditoria (
        id_divipole, observ_jud, re_count_si, re_count_no, count_req_by, on_behalf_of,
        firma_j1, firma_j2, firma_j3, firma_j4, firma_j5, firma_j6,
        firma_cc_j1, firma_cc_j2, firma_cc_j3, firma_cc_j4, firma_cc_j5, firma_cc_j6
    )
    VALUES (
        v_id_divipole, p_aud_observ_jud, p_aud_re_count_si, p_aud_re_count_no, p_aud_count_req_by, p_aud_on_behalf_of,
        p_aud_firma_j1, p_aud_firma_j2, p_aud_firma_j3, p_aud_firma_j4, p_aud_firma_j5, p_aud_firma_j6,
        p_aud_firma_cc_j1, p_aud_firma_cc_j2, p_aud_firma_cc_j3, p_aud_firma_cc_j4, p_aud_firma_cc_j5, p_aud_firma_cc_j6
    )
    RETURNING id INTO v_id_auditoria;

    -- 7. Insertar auditoria_precision
    INSERT INTO public.auditoria_precision (
        id_auditoria, campo_nombre, valor_extraido
    )
    SELECT
        v_id_auditoria,
        u.campo_nombre::VARCHAR(20),
        u.valor_extraido::NUMERIC(5,2)
    FROM UNNEST(p_ap_campos, p_ap_valores) AS u(campo_nombre, valor_extraido);

    IF v_err_duplicado_mesa THEN
        RETURN QUERY SELECT 'duplicate_station_flagged'::TEXT, v_id_divipole;
    ELSE
        RETURN QUERY SELECT 'success'::TEXT, v_id_divipole;
    END IF;
END;
$$;

GRANT EXECUTE ON FUNCTION public.insert_e14_atomic TO anon, authenticated;