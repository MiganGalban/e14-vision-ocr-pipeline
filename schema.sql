-- 1. CATÁLOGO DIVIPOLE REGISTRADURÍA (Fase 1: Universo Estadístico)
CREATE TABLE IF NOT EXISTS public.divipole_regis (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    dd VARCHAR,
    mm VARCHAR,
    zz VARCHAR,
    pp VARCHAR,
    departamento TEXT,
    municipio TEXT,
    puesto TEXT,
    mujeres BIGINT,
    hombres BIGINT,
    total BIGINT,
    mesas_domingo BIGINT,
    comuna TEXT,
    direccion TEXT,
    latitud VARCHAR,
    longitud VARCHAR,
    CONSTRAINT uk_divipole_codigo UNIQUE (dd, mm, zz, pp)
);

ALTER TABLE public.divipole_regis ENABLE ROW LEVEL SECURITY;
CREATE POLICY "Permitir lectura publica divipole_regis" ON public.divipole_regis FOR SELECT TO anon USING (true);
GRANT SELECT ON TABLE public.divipole_regis TO anon, authenticated;


-- 2. CABECERA Y METADATOS DEL FORMULARIO E-14 (Fase 2)
CREATE TABLE IF NOT EXISTS public.divipole (
    id INTEGER GENERATED ALWAYS AS IDENTITY PRIMARY KEY,
    archivo_origen VARCHAR(32) UNIQUE,
    puesto_id BIGINT REFERENCES public.divipole_regis(id) ON DELETE RESTRICT,
    dp_mesa VARCHAR(3),
    dp_lugr VARCHAR(150),
    cod_x VARCHAR(15),
    s_cod_x NUMERIC(3, 2),
    cod_x_2 VARCHAR(15),
    s_cod_x_2 NUMERIC(3, 2),
    barras_1 VARCHAR(20),
    s_barras_1 NUMERIC(3, 2),
    barras_2 VARCHAR(20),
    s_barras_2 NUMERIC(3, 2),
    req_revision BOOLEAN DEFAULT FALSE,
    CONSTRAINT uk_puesto_mesa UNIQUE (puesto_id, dp_mesa)
);

ALTER TABLE public.divipole ENABLE ROW LEVEL SECURITY;
CREATE POLICY "Permitir lectura publica divipole" ON public.divipole FOR SELECT TO anon USING (true);
CREATE POLICY "Permitir insercion anon divipole" ON public.divipole FOR INSERT TO anon WITH CHECK (true);
GRANT SELECT, INSERT ON TABLE public.divipole TO anon, authenticated;


