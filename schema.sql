    flag_baja_conf_votos BOOLEAN NOT NULL DEFAULT FALSE,
    flag_caracter_anomalo BOOLEAN NOT NULL DEFAULT FALSE,
    flag_descuadre_aritmetico BOOLEAN NOT NULL DEFAULT FALSE,
